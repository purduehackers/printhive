const post = (path: string, data: unknown, cookie = '', origin = h.origin) => fetch(h.origin + path, {
  method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', Cookie: cookie }, body: JSON.stringify(data),
});
async function submit(title: string, supports: string, infill: number, layer_height: number) {
  const file = await readFile('tests/support-bracket.stl');
  const response = await post('/api/submissions', submission({ title, supports, infill, layer_height, file_size: file.length }));
  assert.equal(response.status, 201, await response.clone().text());
  const { id, capability } = await response.json();
  const upload = await fetch(`${h.origin}/api/submissions/${id}/file`, { method: 'PUT', headers: { Origin: h.origin, Authorization: `Bearer ${capability}` }, body: file });
  assert.equal(upload.status, 200, await upload.clone().text());
  const token = new URL(h.messages.at(-1)!.match(/http[^\s]+\/confirm\?token=[^\s]+/)![0]).searchParams.get('token')!;
  const confirmed = await fetch(h.origin + '/confirm', { method: 'POST', headers: { Origin: h.origin }, body: new URLSearchParams({ token }) });
  assert.equal(confirmed.status, 200);
  return id as string;
}
